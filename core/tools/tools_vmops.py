# 由 config/cloud-image-presets.json 的 mirror_repo_support 字段生成「镜像×发行版」可用性表 bash 片段，
# 注入 cloud_create 工具脚本，避免把门控写死在 bash 里（运维改 JSON 即可调整，无需动脚本）。
# 每个发行版生成形如 `case "$MIRROR_KEY" in aliyun|huawei) CAN_ANOLIS=1 ;; *) CAN_ANOLIS=0 ;; esac` 的分支；
# 发行版键名需与脚本里的 CAN_<UPPER> 变量对应（anolis→CAN_ANOLIS / openeuler→CAN_OPENEULER）。
def _build_mirror_repo_support_bash(support):
    lines = []
    for distro, mirrors in support.items():
        var = "CAN_" + str(distro).upper()
        pat = "|".join(str(m) for m in mirrors) if mirrors else "__never__"
        lines.append('    case "$MIRROR_KEY" in')
        lines.append('      %s) %s=1 ;;' % (pat, var))
        lines.append('      *) %s=0 ;;' % var)
        lines.append('    esac')
    return "\n".join(lines) + "\n"


_REPO_SUPPORT_BASH = _build_mirror_repo_support_bash(load_mirror_repo_support())

